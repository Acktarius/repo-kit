"""contre-attaque canonical findings sync, assessment report, and coding-agent handoff."""
from __future__ import annotations

import hashlib
import json
import os
import re
from datetime import datetime
from typing import Any

import ca_state as st
from ca_intel import PROVIDER_CAPABILITIES, iso

FINDINGS_REL = os.path.join("security", "findings-reviewed.json")
SCHEMA_REL = os.path.join("security", "findings.schema.json")
ACCEPTED_RISKS_REL = os.path.join("security", "accepted-risks.md")
SOURCE_PREFIX = "contre-attaque (agent-generated, not human-approved)"
AGENT_FIELDS = ("title", "status", "severity", "confidence", "files", "summary",
                "exploitPath", "remediation", "duplicateOf", "acceptedRiskId", "notes")
UNKNOWN_MITIGATION = "unknown: no fix or mitigation identified in collected sources"


def _fields_hash(record: dict[str, Any]) -> str:
    material = {k: record.get(k) for k in AGENT_FIELDS}
    return hashlib.sha256(json.dumps(material, sort_keys=True).encode()).hexdigest()


def _sg_number(sg_id: str) -> int:
    m = re.match(r"^SG-(\d+)$", sg_id or "")
    return int(m.group(1)) if m else 0


def _next_sg(findings: list[dict[str, Any]]) -> str:
    nums = [_sg_number(f.get("id", "")) for f in findings]
    width = max([3] + [len(str(f.get("id", ""))) - 3 for f in findings if _sg_number(f.get("id", ""))])
    return f"SG-{(max(nums) if nums else 0) + 1:0{width}d}"


def _verification(cand: dict[str, Any], a: dict[str, Any]) -> list[str]:
    if a.get("verification"):
        return list(a["verification"])
    comp = cand["component"]
    steps = []
    if cand.get("fixed_versions"):
        steps.append(f"{comp['source']} resolves {comp['name']} to a version outside the advisory's affected "
                     f"ranges (advisory-listed fixes: {', '.join(cand['fixed_versions'])}).")
    steps.append(f"Rerun /contre-attaque at the new commit; {cand['candidate_id']} must be reported as "
                 f"`fixed` or `not_affected` with recorded evidence.")
    steps.append("Run the project's existing test suite for the affected area.")
    return steps


def _acceptance(cand: dict[str, Any], a: dict[str, Any], sg_id: str | None) -> list[str]:
    if a.get("acceptance"):
        return list(a["acceptance"])
    ref = sg_id or cand["candidate_id"]
    return [
        f"No inventoried component resolves to an affected version of {cand['canonical_id']}.",
        f"contre-attaque records {cand['candidate_id']} as fixed/not_affected with evidence at the new commit.",
        f"A human reviewer updates {ref} in security/findings-reviewed.json; the agent never marks it fixed.",
    ]


def _mitigation(cand: dict[str, Any], a: dict[str, Any]) -> str | None:
    if a.get("mitigation"):
        return a["mitigation"]
    comp = cand["component"]
    if cand.get("fixed_versions") and comp["kind"] == "library":
        return f"Upgrade {comp['name']} to an advisory-listed fixed version ({', '.join(cand['fixed_versions'])})."
    return None


def _evidence_lines(a: dict[str, Any]) -> list[str]:
    out = []
    for ev in a.get("evidence") or []:
        if ev["kind"] == "file":
            loc = ev["path"] + (f":{ev['line_start']}" if ev.get("line_start") else "")
            if ev.get("line_end") and ev.get("line_end") != ev.get("line_start"):
                loc += f"-{ev['line_end']}"
            out.append(f"{loc} (sha256 {str(ev.get('sha256'))[:12]})")
        elif ev["kind"] == "url":
            out.append(f"{ev['url']} (evidence {ev['evidence'][:12]}{', discovery lead' if ev.get('lead') else ''})")
        else:
            out.append(ev.get("description") or json.dumps(ev, sort_keys=True))
    return out


def _source_refs(cand: dict[str, Any]) -> list[str]:
    refs = []
    for s in cand.get("sources") or []:
        bits = [s.get("provider", "?"), s.get("id") or ""]
        if s.get("modified"):
            bits.append(f"modified {s['modified']}")
        refs.append(" ".join(b for b in bits if b))
    if cand.get("kev"):
        refs.append(f"CISA KEV added {cand['kev'].get('date_added')}")
    return refs


def build_record(cand: dict[str, Any], a: dict[str, Any], run: dict[str, Any], sg_id: str) -> dict[str, Any]:
    comp = cand["component"]
    files = sorted({comp["source"]} | {ev["path"] for ev in a.get("evidence") or [] if ev["kind"] == "file"})
    mitigation = _mitigation(cand, a)
    limitations = list(a.get("unknowns") or []) + [
        f"Version evidence tier: {comp['tier']} ({comp['source']}); the deployed runtime was not observed.",
    ]
    if comp.get("sbom_observed_at"):
        limitations.append(f"SBOM {comp.get('sbom_subject')} observed at {comp['sbom_observed_at']}; "
                           "not proof of current exposure.")
    notes = "\n".join([
        f"Agent-generated by contre-attaque run {run['run_id']} at commit {run['git'].get('commit') or 'unknown'}; "
        "not human-approved. Triage with /security-triage-findings.",
        f"Candidate: {cand['candidate_id']}. Applicability: {a['applicability']} "
        f"(confidence {a['confidence']}, decided {a['decided_at_utc']} by {a['decided_by']}).",
        "Evidence: " + "; ".join(_evidence_lines(a)),
        "Sources: " + "; ".join(_source_refs(cand)),
        f"Known fix/mitigation: {mitigation or UNKNOWN_MITIGATION}",
        "Limitations: " + "; ".join(limitations),
        "Verification: " + " ".join(_verification(cand, a)),
        "Acceptance criteria: " + " ".join(_acceptance(cand, a, sg_id)),
    ])
    return {
        "id": sg_id,
        "title": f"{cand['canonical_id']} affects {comp['name']} {comp.get('version') or ''}".strip(),
        "status": "open",
        "severity": cand["severity"],
        "confidence": a["confidence"],
        "firstSeen": cand["first_seen_utc"],
        "lastReviewed": None,
        "source": f"{SOURCE_PREFIX}: {cand['candidate_id']}; advisories: {', '.join(cand['aliases'])}",
        "files": files,
        "summary": f"{comp['name']} {comp.get('version') or '(version unknown)'} from {comp['source']} "
                   f"is assessed affected by {cand['canonical_id']}. {a['rationale']}",
        "exploitPath": a.get("exploit_path"),
        "remediation": mitigation,
        "duplicateOf": None,
        "acceptedRiskId": None,
        "notes": notes,
    }


def _matches_existing(record: dict[str, Any], cand: dict[str, Any]) -> bool:
    text = " ".join(str(record.get(k) or "") for k in ("title", "source", "summary", "notes"))
    if "contre-attaque" in text and cand["candidate_id"] in text:
        return True
    name = cand["component"]["name"].lower()
    return any(alias in text for alias in cand["aliases"]) and name in text.lower()


def sync_findings(root: str, state: dict[str, Any], run: dict[str, Any], now: datetime) -> dict[str, Any]:
    """Create/refresh agent-generated open records. Caller holds the state lock.

    Records touched by a human since the agent last wrote them are never
    modified; disagreements are returned as conflicts.
    """
    result: dict[str, Any] = {"written": False, "added": [], "updated": [], "unchanged": [],
                              "linked": [], "blocked": [], "conflicts": [], "errors": []}
    fpath, spath = os.path.join(root, FINDINGS_REL), os.path.join(root, SCHEMA_REL)
    if not (os.path.isfile(fpath) and os.path.isfile(spath)):
        result["errors"].append(f"{FINDINGS_REL} or {SCHEMA_REL} missing; install the repo-kit security module. "
                                "No canonical records were written.")
        return result
    try:
        doc, schema = st.load_json(fpath), st.load_json(spath)
        st.validate_schema(doc, schema, "findings")
    except (OSError, ValueError, st.StateError) as exc:
        result["errors"].append(f"existing {FINDINGS_REL} is unreadable or invalid ({exc}); not modified")
        return result
    findings = doc["findings"]
    by_id = {f["id"]: f for f in findings}
    changed = False

    for cid, a in sorted(state["assessments"].items()):
        cand = state["candidates"].get(cid)
        if cand is None:
            continue
        link = state["findings"].get(cid)
        record = by_id.get(link["sg_id"]) if link else None
        if link and record is None:
            if a["applicability"] == "affected":
                result["conflicts"].append(f"{cid}: linked {link['sg_id']} was removed from {FINDINGS_REL}; "
                                           "not recreated (human disposition preserved)")
            continue
        if record is None and a["applicability"] == "affected":
            record = next((f for f in findings if _matches_existing(f, cand)), None)
            if record is not None:
                state["findings"][cid] = {"sg_id": record["id"], "written_fields_sha256": "",
                                          "run_id": run["run_id"], "at_utc": iso(now)}
                link = state["findings"][cid]
        if record is not None:
            human_touched = _fields_hash(record) != link.get("written_fields_sha256")
            if record.get("acceptedRiskId") or record.get("status") == "accepted-risk":
                if a["applicability"] == "affected":
                    result["conflicts"].append(f"{cid}: {record['id']} is an accepted risk "
                                               f"({record.get('acceptedRiskId') or 'no AR id'}); not reopened")
                continue
            if a["applicability"] in ("fixed", "not_affected") and record.get("status") == "open":
                result["conflicts"].append(f"{cid}: {record['id']} is open but current applicability is "
                                           f"{a['applicability']}; a human must verify before any status change")
                continue
            if a["applicability"] != "affected":
                continue
            if record.get("status") != "open":
                result["conflicts"].append(f"{cid}: {record['id']} has status {record['status']} but current "
                                           "applicability is affected; not modified")
                continue
            if cand["severity"] is None:
                result["blocked"].append(f"{cid}: severity unknown; {record['id']} not refreshed")
                continue
            if not link.get("written_fields_sha256"):
                result["linked"].append(f"{cid}: covered by existing {record['id']} (not agent-written; not modified)")
                continue
            proposed = build_record(cand, a, run, record["id"])
            proposed["firstSeen"] = record.get("firstSeen") or proposed["firstSeen"]
            proposed["lastReviewed"] = record.get("lastReviewed")
            if human_touched:
                if _fields_hash(proposed) != _fields_hash(record):
                    result["conflicts"].append(f"{cid}: {record['id']} was edited by a human; agent update "
                                               "not applied (review the handoff for the new evidence)")
                else:
                    result["unchanged"].append(record["id"])
                continue
            if _fields_hash(proposed) == _fields_hash(record):
                result["unchanged"].append(record["id"])
                continue
            record.update(proposed)
            link.update({"written_fields_sha256": _fields_hash(record), "run_id": run["run_id"], "at_utc": iso(now)})
            result["updated"].append(record["id"])
            changed = True
            continue
        if a["applicability"] != "affected":
            continue
        if cand["severity"] is None:
            result["blocked"].append(f"{cid}: affected, but no source-backed severity; canonical record blocked "
                                     "until a human sets severity")
            continue
        sg_id = _next_sg(findings)
        record = build_record(cand, a, run, sg_id)
        findings.append(record)
        by_id[sg_id] = record
        state["findings"][cid] = {"sg_id": sg_id, "written_fields_sha256": _fields_hash(record),
                                  "run_id": run["run_id"], "at_utc": iso(now)}
        result["added"].append(sg_id)
        changed = True

    if changed:
        try:
            st.validate_schema(doc, schema, "findings")
        except st.StateError as exc:
            result["errors"].append(f"prospective {FINDINGS_REL} failed schema validation ({exc}); not written")
            return result
        st.write_json_atomic(fpath, doc)
        st.validate_schema(st.load_json(fpath), schema, "findings")
        result["written"] = True
    return result


